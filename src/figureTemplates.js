// 图表分析 · 三份结构化文档的生成提示词。
// 章节骨架与 latex-writing/.pi/skills/figure-analysis/references/document-contracts.md 保持一致；
// 固化骨架是为了输出结构稳定（每次生成的文档可直接对比、可增量维护）。

const PREAMBLE = (title) =>
  `你正在为论文《${title}》生成「图表分析」结构化文档。请先用 read_paper 工具通读论文（先 outline，再方法与实验章节），定位全部插图（figure）与表格（table）的编号、标题与上下文位置，看懂后再动笔；不要编造。`;

const RULES =
  `通用硬性要求：\n` +
  `- 严格按下方给出的 ## 小节骨架输出，顺序固定、节名一致；某节内容少可以短，不允许缺节或改名\n` +
  `- 每条事实性断言必须带引用锚：图x / 表y / 式z / p.N；拿不准的标注「推断」\n` +
  `- 中文输出，Markdown；表格密集使用；mermaid 代码块按需使用`;

const WRITE_RULE = (path) =>
  `完成后必须用 write 工具把成品写入：${path}（UTF-8 Markdown）。写入成功后回复一句话确认；除该文件外不要写任何其他文件。`;

export const FIGURE_FILES = [
  { key: "struct", file: "方法结构分析.md", label: "方法结构分析", icon: "🧩" },
  { key: "expr", file: "实验设计解析.md", label: "实验设计解析", icon: "🧪" },
  { key: "repro", file: "复现大纲.md", label: "复现大纲", icon: "🗺" },
];

export function figureFilePath(slug, file) {
  return `knowledge/图表分析/${slug}/${file}`;
}

export function buildFigurePrompt(kind, { title, slug }) {
  const def = FIGURE_FILES.find((f) => f.key === kind);
  if (!def) throw new Error("未知的图表分析文档类型");
  const out = figureFilePath(slug, def.file);
  const head = PREAMBLE(title) + "\n\n" + RULES + "\n\n";

  if (kind === "struct") {
    return head +
      `生成《方法结构分析》。逐节骨架：

## 0. 方法一句话
## 1. 方法总览图解析
组件清单表（列：组件 / 图中位置 / 对应公式 / 作用），覆盖论文的主要方法图（图1 为主，其余方法类图逐个给出）。
## 2. 图-公式-组件串联（数据流）
逐条链路描述：输入是什么 → 经过组件A（式x）→ 组件B（式y）→ 输出什么；每条链路标注对应 图n。分支、回路、多阶段必须如实画。
## 3. 写作逻辑：图的位置与论证功能
每个图回答：它为什么放在那个位置、支撑哪一节/哪段的主张、全文叙事线如何靠图推进（从问题图景 → 方法全景 → 机制细节 → 证据）。
## 4. 更改与改进逻辑
改动传播表（列：改动点 / 受影响的箭头与公式 / 受影响的实验表 / 改动代价估计），至少 4 行；
改进切入点 ≥3 条（每条：切入点 → 为什么可行 → 需要重新验证哪些实验）。
## 5. 关键点速查
5–8 条，每条带 图x / 式y / p.N 引用。

${WRITE_RULE(out)}`;
  }

  if (kind === "expr") {
    return head +
      `生成《实验设计解析》。逐节骨架：

## 0. 实验全景一句话
## 1. 实验总览
表（列：表y / 回答的问题 / 类型[主结果·消融·泛化·效率] / 关键设置），覆盖论文全部实验表格。
## 2. 逐表解析
每张表一个小节：行列含义 / 自变量与因变量 / 对照组（baseline）是谁 / 公平性设置（同规模？同推理预算？同训练量？）/ 该表支持的结论。
## 3. 实验设计教学
拆解本文的设计套路（为什么先主结果再消融、对照组怎么选、结论怎么从表格里"读"出来）；
最后给「做同类研究的实验清单」可迁移模板（按顺序列出该做哪些实验、每类回答什么问题）。
## 4. 关键数字速查
表（列：数字 / 含义 / 出处表y），8–15 行。

${WRITE_RULE(out)}`;
  }

  // repro
  return head +
    `生成《复现大纲》。逐节骨架：

## 0. 复现目标一句话
## 1. 声称清单
C1..Cn（列：编号 / 具体数字或结论 / 出处表y），只收可验证的量化声称，5–10 条。
## 2. 实验总括大纲
一个 \`\`\`mermaid 代码块（flowchart LR）：数据 → 预处理 → 训练 → 评估 → 各表产出 的完整流水线，把论文实验流程穿起来；节点 ≤14 字；多阶段/分支如实画。
## 3. 复现步骤分层
smoke / eval-like / full 三层（与 paper-reproduce 技能 S6 对齐）：每层做什么、预期看到什么、通过标准。
## 4. 资源需求
数据 / 算力（估算显存与时长）/ 代码仓库 / 人力，分条列出。
## 5. 风险点与坑
环境世代、实现歧义、论文未写的隐藏超参等，逐条列。
## 6. 改进定位表
表（列：环节 / 现状 / 弱点 / 改进方向 / 预期收益 / 风险），至少 3 行——这是用户"知道改进到哪"的落点，要具体到数据/训练/推理/评估的某一环。

${WRITE_RULE(out)}`;
}
