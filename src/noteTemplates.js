// 粗读知识产出的四个生成模板：全部通过 pi agent（read_paper 阅读 + write 落盘）完成。
// 每个模板写死输出路径，保证笔记只落在 knowledge/粗读/<slug>/ 下，与精读目录互不可混。

const PREAMBLE = (title) =>
  `你正在为论文《${title}》生成「粗读」知识笔记。请先用 read_paper 工具阅读摘要、引言、结论（必要时补看各节首段与图表标题），看懂后再动笔；不要凭空编造。`;

const WRITE_RULE = (path) =>
  `完成后必须用 write 工具把成品写入文件：${path}（UTF-8、Markdown）。写入成功后回复一句话确认即可；除该文件外不要写任何其他文件。`;

export const NOTE_FILES = [
  { key: "note", file: "粗读解析.md", label: "粗读解析", icon: "📝" },
  { key: "mindmap", file: "思维导图.md", label: "思维导图", icon: "🧠" },
  { key: "flow", file: "流程图.md", label: "流程图", icon: "🗺" },
  { key: "algo", file: "算法迭代图.md", label: "算法迭代图", icon: "🔁" },
];

export function noteFilePath(slug, file) {
  return `knowledge/粗读/${slug}/${file}`;
}

export function buildPrompt(kind, { title, slug }) {
  const file = NOTE_FILES.find((f) => f.key === kind);
  if (!file) throw new Error("未知的笔记类型");
  const out = noteFilePath(slug, file.file);
  const head = PREAMBLE(title) + "\n\n";

  if (kind === "note") {
    return head +
      `请生成「粗读解析」笔记，向没读过论文的人交代清楚作者为什么写这篇论文。要求：中文、总长 800–1200 字、关键论断标注页码 (p.N)、用以下小节结构（## 级别）：

## 背景与动机
这个领域在解决什么问题；作者为什么要写这篇论文（研究缺口/痛点）；写之前已有方法是什么、哪里不够用。
## 要解决的问题
一句话问题定义；具体挑战与约束条件。
## 方法概览
核心思路一段话 + 关键机制要点列表（每点一句话）。
## 主要结论
最重要的实验结果与论断（带关键数字）。
## 局限与不足
作者自述的局限 + 你分析出的潜在局限。
## 技术必要性
为什么非走这条技术路线不可；替代路线分别为什么不行；如果不做这个工作会怎样。

${WRITE_RULE(out)}`;
  }

  if (kind === "mindmap") {
    return head +
      `请生成一份用于 markmap 思维导图渲染的 Markdown 大纲。这是内容导图，不是目录抄写——节点必须写实质内容（机制、结论、关系、数字），不要照抄论文章节标题。要求：

- 根节点（# 一级）：论文核心贡献，一句话
- 二级（##）：固定五大主干——核心问题 / 关键洞察 / 方法组件 / 实验验证 / 局限与展望
- 三级及以下：拆出实质节点——每个方法组件说明「机制+作用」，实验节点给出关键数字结论，洞察节点点明与前人做法的本质差异
- 层级 3–4 层；每个父节点下 ≤6 个子节点；每个节点 ≤20 字
- 只输出 Markdown 大纲本身，不要解释性文字、不要代码块包裹

${WRITE_RULE(out)}`;
  }

  if (kind === "flow") {
    return head +
      `请梳理论文的论证脉络与方法流水线，生成包含 mermaid 流程图的笔记。文件内容 = 一句导语 + 至少一个 \`\`\`mermaid 代码块（flowchart TD）：

- 覆盖完整脉络：问题动机 → 关键假设/洞察 → 方法各步骤（含数据流走向）→ 实验验证 → 结论
- 节点文字为简洁中文短语（≤12 字）；用 subgraph 划分「问题层 / 方法层 / 验证层」
- 方法有分支、回路、多阶段训练的必须如实体现（如两阶段训练、交替优化、外循环/内循环）
- mermaid 代码块前后可各加 1–2 句文字说明阅读要点

${WRITE_RULE(out)}`;
  }

  // algo：算法迭代图（可无）
  return head +
    `请分析论文提出的方法是否存在「实打实的迭代过程」：版本演进（v1→v2）、消融驱动的逐步改进、从 baseline 到最终方法的多步优化、训练/推理流程的多阶段设计都算；若全文只是一个单一静态方法则不算。

若存在，请生成包含 mermaid 图的笔记：一个 \`\`\`mermaid 代码块（graph LR），按时间/逻辑顺序展示每一步迭代——
- 节点 = 该版本/阶段的核心设计（≤14 字）
- 相邻节点之间的边上标注「暴露的问题 → 针对性改进」（用 | 标签，≤18 字）
- 图前用 2–3 句话交代迭代主线，图后列出每步迭代带来的可量化提升（若有）

若论文不涉及算法迭代：不要写任何文件，并在回复第一行单独输出：[[无需生成]]，随后用一句话说明原因。

${WRITE_RULE(out)}`;
}

// 精读笔记：走主对话（用户手动发送），写入 knowledge/精读/<slug>/
export function buildFineNotePrompt({ title, slug }) {
  return `请精读论文《${title}》，生成一份深度精读笔记，并用 write 工具写入：knowledge/精读/${slug}/精读笔记.md（UTF-8、Markdown）。

要求（参考结构，可按论文特点增删小节；密集使用 GFM 表格、$$/\$ 公式、⚠️ 易错点提示，关键内容标注页码 (p.N)）：

## 0. 一句话概括
## 1. 名词基础（术语表：术语/全称/含义，标注易混淆项）
## 2. 背景与动机（为什么是这条技术路线；候选方案对比）
## 3. 核心思想（概念辨析 + 直观例子）
## 4. 方法细节（逐步拆解，含编号公式与各项含义）
## 5. 输入输出结构辨析（伪代码 + 常见误解三连否）
## 6. 实验速览（结果表：项目/结果/依据）
## 7. 相关方法对比（对比表）
## 8. 摘要复述模板 + 记忆链（一行因果链）
## 9. 待深入清单（- [ ] 任务）

先创建目录再写文件；写完后回复一句话确认。`;
}
