import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { createSessionEventChannel } from "../src/sessionEventChannel.js";
import { studyFixture, mockStudyResponse } from "./helpers/study-fixture.mjs";

test("notes retain selected text, tables, images and translations through concurrent generation, restart and export", { timeout: 60000 }, async t => {
  let generating, release;
  const f = await studyFixture({ thinkingText: "核对原文和证据。", respond: async (req, text) => {
    if (text.includes('"study_lesson"') && generating) { generating(); await new Promise(r => { release = r; }); }
    if (req.messages.at(-1).role === "user" && text === "调用论文工具") return { tool_calls: [{ index: 0, id: "read-test", type: "function", function: { name: "read_paper", arguments: JSON.stringify({ mode: "outline" }) } }] };
    return mockStudyResponse(req, text) ?? "已读取论文结构。";
  } });
  const guideState = {}, chatState = {}, guideEvents = [], chatEvents = [];
  const guide = createSessionEventChannel({ state: guideState, fetch: (u, o) => fetch(f.url + u, o) });
  const chat = createSessionEventChannel({ state: chatState, fetch: (u, o) => fetch(f.url + u, o) });
  t.after(async () => { release?.(); guide.closeSessionEvents(); chat.closeSessionEvents(); await f.dispose(); });
  const cacheFile = path.join(f.parsed, "blocks.json"), document = JSON.parse(fs.readFileSync(cacheFile));
  const image = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==", "base64");
  fs.writeFileSync(path.join(f.parsed, "figure.png"), image);
  document.blocks.push({ id: "figure", type: "image", page: 1, caption: "Figure 1. Routing pipeline.", src: "file/figure.png" });
  fs.writeFileSync(cacheFile, JSON.stringify(document));
  const uploaded = await fetch(f.url + "/api/studies/import", { method: "PUT", headers: { "Content-Type": "application/pdf", "X-Filename": "Notes.pdf" }, body: f.pdf });
  let task = await uploaded.json();
  const raw = async (route, body, method = body ? "POST" : "GET", state = guideState) => {
    const response = await fetch(f.url + "/api" + route, { method, headers: { "Content-Type": "application/json", "X-Pi-Control": state.controlId || "" }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, value: await response.json() };
  };
  const api = async (...args) => { const r = await raw(...args); assert.ok(r.status < 300, JSON.stringify(r)); return r.value; };
  const refresh = async () => { task = (await api(`/studies/${task.id}`)).task; };
  const run = async (action, body = {}) => { await guide.waitOperation((await api(`/studies/${task.id}/${action}`, body)).operationId); await refresh(); };
  await guide.connectSessionEvents(task.guideSessionId, event => guideEvents.push(event));
  await chat.connectSessionEvents(task.chatSessionId, event => chatEvents.push(event));
  await run("prepare");
  let notes = await api(`/studies/${task.id}/notes`);
  notes = await api(`/studies/${task.id}/notes`, { markdown: "# 我的理解\n", revision: notes.revision }, "PATCH");
  assert.equal((await raw(`/studies/${task.id}/notes`, { markdown: "旧页面", revision: 0 }, "PATCH")).status, 409);
  notes = await api(`/studies/${task.id}/notes/append`, { revision: notes.revision, blockIds: ["abstract"], text: "Accuracy is 95%" });
  assert.match(notes.markdown, /Accuracy is 95%/); assert.ok(!notes.markdown.includes("two-stage baseline"));
  notes = await api(`/studies/${task.id}/notes/append`, { revision: notes.revision, blockIds: ["table", "figure"] });
  assert.match(notes.markdown, /<table>/);
  const attachment = /!\[Figure.*?\]\(([^)]+)\)/.exec(notes.markdown)[1];
  assert.deepEqual(Buffer.from(await (await fetch(f.url + attachment)).arrayBuffer()), image);
  assert.equal((await raw(`/studies/${task.id}/notes/append`, { revision: notes.revision, blockIds: ["abstract"], translated: true })).status, 409);
  await run("translate", { blockIds: ["abstract", "table"] });
  notes = await api(`/studies/${task.id}/notes/append`, { revision: notes.revision, blockIds: ["abstract", "table"], translated: true });
  assert.match(notes.markdown, /中文译文/); assert.match(notes.markdown, /\$x_1=2\$/);

  const started = new Promise(r => { generating = r; });
  const operation = await api(`/studies/${task.id}/lesson`, { checkpointId: "rough_0" });
  await started;
  notes = await api(`/studies/${task.id}/notes`, { markdown: notes.markdown + "\n生成期间记下的新想法", revision: notes.revision }, "PATCH");
  const prompt = await api(`/sessions/${task.chatSessionId}/prompt`, { text: "调用论文工具" }, "POST", chatState);
  await chat.waitOperation(prompt.operationId); release(); generating = null;
  await guide.waitOperation(operation.operationId); await refresh();
  assert.equal(task.notes.markdown, notes.markdown, "a model commit must not overwrite simultaneous notes");
  assert.ok(guideEvents.some(e => e.t === "study_activity" && e.activity.steps.some(s => s.thinking?.includes("核对原文"))));
  assert.ok(chatEvents.some(e => e.t === "thinking"));
  assert.ok(chatEvents.some(e => e.t === "tool_start" && e.name === "read_paper"));
  assert.ok(chatEvents.some(e => e.t === "tool_end" && e.name === "read_paper"));
  assert.ok(!chatEvents.some(e => e.t === "study_activity"));
  assert.ok(!guideEvents.some(e => e.t === "tool_start" && e.name === "read_paper"));
  assert.ok(task.activities.some(a => a.kind === "lesson" && a.status === "completed" && a.steps.some(s => s.name === "search_library")));
  guide.closeSessionEvents(); chat.closeSessionEvents(); await f.restart(); await refresh();
  assert.equal(task.notes.markdown, notes.markdown);
  assert.ok(task.activities.some(a => a.steps.some(s => s.thinking?.includes("核对原文"))));
  const history = await api(`/sessions/${task.chatSessionId}`);
  assert.ok(history.messages.some(m => m.parts.some(p => p.type === "thinking")));
  assert.ok(history.messages.some(m => m.role === "toolResult" && m.toolName === "read_paper"));
  await guide.connectSessionEvents(task.guideSessionId, () => {});
  await run("export");
  const saved = fs.readFileSync(path.join(f.directory, "knowledge", "论文研读", task.id, "阅读笔记.md"), "utf8");
  assert.ok(!saved.includes(`/api/studies/${task.id}/assets/`));
  const archivedImage = attachment.replace(`/api/studies/${task.id}/assets/`, `/api/study-library/${task.id}/assets/`);
  guide.closeSessionEvents();
  await api(`/studies/${task.id}`, undefined, "DELETE");
  assert.deepEqual(Buffer.from(await (await fetch(f.url + archivedImage)).arrayBuffer()), image);
  assert.match(saved, /生成期间记下的新想法/);
});
